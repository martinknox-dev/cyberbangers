"""Phase 5 regulatory export: SAR (Suspicious Activity Report) and STR (Suspicious Transaction Report).

Extends the existing dossier generator to produce RBI/FIU-IND compliant formats.
"""

from __future__ import annotations

import io
import json
import re
from datetime import UTC, datetime

import polars as pl

from export.dossier import InvestigationDossier


class SARExporter:
    """Export investigation dossier as SAR (Suspicious Activity Report) JSON.

    Follows FIU-IND SAR format guidelines for Indian financial institutions.
    """

    def export_sar(self, dossier: InvestigationDossier, reporting_entity: str) -> str:
        """Generate SAR JSON from an investigation dossier.

        Args:
            dossier: Completed investigation dossier with risk summary and indicators.
            reporting_entity: Identifier of the reporting entity (e.g., "BANK001").

        Returns:
            SAR report as formatted JSON string.
        """
        risk = dossier.risk_summary
        subject_accounts = dossier.subject_accounts

        # Collect all grounds for suspicion from indicators
        grounds = []
        for indicator in dossier.indicators:
            grounds.append({
                "account": indicator.indicator,  # Using indicator name as account ref
                "indicator": indicator.indicator,
                "method": indicator.method,
                "value": indicator.value,
                "explanation": indicator.explanation,
            })

        # Build suspicious activity summary
        suspicious_activity = {
            "risk_score": round(risk.risk_score, 2) if risk else 0.0,
            "risk_band": risk.risk_band if risk else "LOW",
            "operational_role": risk.operational_role if risk else "STANDARD_ACCOUNT",
            "domain_score": round(risk.domain_score, 2) if risk else 0.0,
            "anomaly_score": round(risk.anomaly_score, 2) if risk else 0.0,
            "top_archetype": risk.top_archetype if risk else "No domain indicator",
            "retained_tainted_amount": round(risk.retained_tainted_amount, 2) if risk else 0.0,
            "freeze_priority_score": round(risk.freeze_priority_score, 2) if risk else 0.0,
        }

        # Add sub-scores if available
        if risk and risk.sub_scores:
            suspicious_activity["sub_scores"] = [
                {
                    "domain": s.domain,
                    "label": s.label,
                    "value": round(s.value, 2),
                    "weight": round(s.weight, 1),
                    "points": round(s.points, 2),
                }
                for s in risk.sub_scores
            ]

        sar = {
            "report_type": "SAR",
            "reporting_entity": reporting_entity,
            "subject_accounts": subject_accounts,
            "suspicious_activity": suspicious_activity,
            "grounds_for_suspicion": grounds,
            "generated_at": datetime.now(UTC).isoformat(),
            "disclaimer": (
                "This report is generated by an automated analytical system. "
                "It contains investigative leads, not legal evidence. "
                "Human review required before regulatory filing."
            ),
        }

        return json.dumps(sar, indent=2, default=str)


class STRExporter:
    """Export investigation dossier as STR (Suspicious Transaction Report) CSV.

    Follows FIU-IND STR format for transaction-level reporting.
    """

    def export_str(self, dossier: InvestigationDossier, reporting_entity: str) -> str:
        """Generate STR CSV from an investigation dossier.

        Args:
            dossier: Completed investigation dossier.
            reporting_entity: Identifier of the reporting entity (e.g., "BANK001").

        Returns:
            STR report as CSV string with headers.
        """
        risk = dossier.risk_summary

        rows = []
        for indicator in dossier.indicators:
            row = {
                "report_type": "STR",
                "reporting_entity": reporting_entity,
                "subject_account": indicator.indicator,  # Using indicator as proxy
                "counterparty": "",
                "indicator_type": indicator.indicator,
                "method": indicator.method,
                "value": indicator.value,
                "unit": indicator.unit,
                "txn_ids": ",".join(indicator.txn_ids) if indicator.txn_ids else "",
                "risk_score": round(risk.risk_score, 2) if risk else 0.0,
                "risk_band": risk.risk_band if risk else "LOW",
                "operational_role": risk.operational_role if risk else "STANDARD_ACCOUNT",
                "retained_tainted_amount": round(risk.retained_tainted_amount, 2) if risk else 0.0,
                "freeze_priority_score": round(risk.freeze_priority_score, 2) if risk else 0.0,
                "generated_at": datetime.now(UTC).isoformat(),
            }
            rows.append(row)

        # Also add a summary row for the account overall
        # Compute total amount from facts/indicators
        total_amount = 0.0
        for fact in dossier.facts:
            if fact.category in ("LEDGER", "TRANSACTION"):
                try:
                    match = re.search(r'₹([\d,]+\.?\d*)', str(fact.value))
                    if match:
                        total_amount += float(match.group(1).replace(',', ''))
                except (ValueError, AttributeError):
                    pass

        for account_no in dossier.subject_accounts:
            rows.append({
                "report_type": "STR",
                "reporting_entity": reporting_entity,
                "subject_account": account_no,
                "counterparty": "",
                "indicator_type": "SUMMARY",
                "method": "RISK_SUMMARY",
                "value": total_amount if total_amount > 0 else (risk.risk_score if risk else 0.0),
                "unit": "rupees" if total_amount > 0 else "score",
                "txn_ids": "",
                "risk_score": round(risk.risk_score, 2) if risk else 0.0,
                "risk_band": risk.risk_band if risk else "LOW",
                "operational_role": risk.operational_role if risk else "STANDARD_ACCOUNT",
                "retained_tainted_amount": round(risk.retained_tainted_amount, 2) if risk else 0.0,
                "freeze_priority_score": round(risk.freeze_priority_score, 2) if risk else 0.0,
                "generated_at": datetime.now(UTC).isoformat(),
            })

        df = pl.DataFrame(rows)
        output = io.StringIO()
        df.write_csv(output)
        return output.getvalue()


__all__ = ["SARExporter", "STRExporter"]